-- A task changes once: OPEN -> DONE, setting only its completion fields.
CREATE FUNCTION baec.crm_tasks_guard() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'crm_tasks rows are never deleted' USING ERRCODE = 'restrict_violation';
    END IF;
    IF OLD.status <> 'OPEN' OR NEW.status <> 'DONE'
       OR (NEW.organization_id, NEW.workspace, NEW.task_id, NEW.account_id, NEW.contact_id, NEW.title, NEW.due_date,
           NEW.priority, NEW.notes, NEW.created_at, NEW.created_by, NEW.seq)
          IS DISTINCT FROM
          (OLD.organization_id, OLD.workspace, OLD.task_id, OLD.account_id, OLD.contact_id, OLD.title, OLD.due_date,
           OLD.priority, OLD.notes, OLD.created_at, OLD.created_by, OLD.seq) THEN
        RAISE EXCEPTION 'a task can only be completed, once' USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
END $$;

-- An activity changes once: its Engine 1 interaction link is set when it was empty. Nothing else changes.
CREATE FUNCTION baec.crm_activities_guard() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'crm_activities rows are never deleted' USING ERRCODE = 'restrict_violation';
    END IF;
    IF OLD.engine1_interaction_id IS NOT NULL OR NEW.engine1_interaction_id IS NULL
       OR (NEW.organization_id, NEW.workspace, NEW.activity_id, NEW.account_id, NEW.contact_id, NEW.interaction_type,
           NEW.occurred_at, NEW.raw_notes, NEW.summary, NEW.buyer_role, NEW.buyer_statement, NEW.seller_notes,
           NEW.ai_assisted, NEW.created_at, NEW.created_by, NEW.seq)
          IS DISTINCT FROM
          (OLD.organization_id, OLD.workspace, OLD.activity_id, OLD.account_id, OLD.contact_id, OLD.interaction_type,
           OLD.occurred_at, OLD.raw_notes, OLD.summary, OLD.buyer_role, OLD.buyer_statement, OLD.seller_notes,
           OLD.ai_assisted, OLD.created_at, OLD.created_by, OLD.seq) THEN
        RAISE EXCEPTION 'an activity can only be linked to Engine 1, once' USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER crm_tasks_guard BEFORE UPDATE OR DELETE ON baec.crm_tasks
    FOR EACH ROW EXECUTE FUNCTION baec.crm_tasks_guard();
CREATE TRIGGER crm_activities_guard BEFORE UPDATE OR DELETE ON baec.crm_activities
    FOR EACH ROW EXECUTE FUNCTION baec.crm_activities_guard();

DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['identity_audit', 'account_ownership', 'account_meta', 'interaction_meta',
                             'condition_drafts', 'draft_resolutions', 'preparation_requests', 'preparations',
                             'preparation_edits', 'preparation_reviews', 'preparation_provenance',
                             'preparation_blocks', 'events', 'attributions', 'crm_contacts',
                             'crm_interaction_links'] LOOP
        EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE OR DELETE ON baec.%I '
                       'FOR EACH ROW EXECUTE FUNCTION baec.refuse_change()', t || '_append_only', t);
    END LOOP;
    -- TRUNCATE skips row triggers and row-level security, so it is refused on every table, for every role.
    FOREACH t IN ARRAY ARRAY['organizations', 'users', 'identity_audit', 'account_ownership', 'account_meta',
                             'interaction_meta', 'condition_drafts', 'draft_resolutions', 'preparation_requests',
                             'preparations', 'preparation_edits', 'preparation_reviews', 'preparation_provenance',
                             'preparation_blocks', 'events', 'attributions', 'crm_contacts', 'crm_tasks',
                             'crm_interaction_links', 'crm_activities'] LOOP
        EXECUTE format('CREATE TRIGGER %I BEFORE TRUNCATE ON baec.%I '
                       'FOR EACH STATEMENT EXECUTE FUNCTION baec.refuse_change()', t || '_no_truncate', t);
    END LOOP;
END $$;

