-- 0001: BAEC product schema (identity, console, CRM). Runs as the migration role, which owns every object here.
--
-- Mirrors identity.py (identity V2), console_store.py (console V4), and crm_store.py (CRM V2). Differences:
--   * every tenant row carries organization_id, and every row of a workspace store carries workspace ('local' or
--     'synthetic'), so rows that lived in separate SQLite files keep their own ids side by side;
--   * keys and foreign keys include (organization_id, workspace), so a row can only reference a row of its own
--     organization: a cross-tenant relationship is a foreign-key violation, not an application check;
--   * timestamps are timestamptz (the same instant; the stored offset is not kept);
--   * JSON columns stay exact text (CHECK IS JSON), so stored drafts and preparations are byte-for-byte what the
--     console wrote;
--   * seq records insertion order (the SQLite stores order by rowid);
--   * rows are append-only except the mutations the stores perform: user rename/activation, task completion, and
--     linking an activity to Engine 1 once (implementation choice: tables SQLite left mutable but never mutated,
--     such as account_meta and contacts, refuse changes here).
-- Engine 1 and Engine 2 records are not here: they remain in their SQLite stores (docs/V04_PHASE3_POSTGRES_RLS_REPORT.md).

CREATE SCHEMA baec;

-- The organization the current transaction acts for, or NULL when none is set. Set only with
-- set_config('baec.organization_id', <id>, true) (transaction-local; baec_console/postgres/database.py).
CREATE FUNCTION baec.current_organization() RETURNS text
    LANGUAGE sql STABLE
    AS $$ SELECT nullif(pg_catalog.current_setting('baec.organization_id', true), '') $$;

CREATE FUNCTION baec.refuse_change() RETURNS trigger
    LANGUAGE plpgsql
    AS $$ BEGIN RAISE EXCEPTION '% is append-only', TG_TABLE_NAME USING ERRCODE = 'restrict_violation'; END $$;

-- --- identity ---------------------------------------------------------------------------------------------------

CREATE TABLE baec.organizations (
    organization_id text PRIMARY KEY CHECK (btrim(organization_id) <> ''),
    name text NOT NULL CHECK (btrim(name) <> ''),
    created_at timestamptz NOT NULL,
    seq bigint GENERATED ALWAYS AS IDENTITY UNIQUE
);

CREATE TABLE baec.users (
    user_id text PRIMARY KEY CHECK (btrim(user_id) <> ''),
    organization_id text NOT NULL REFERENCES baec.organizations (organization_id),
    display_name text NOT NULL CHECK (btrim(display_name) <> ''),
    created_at timestamptz NOT NULL,
    active boolean NOT NULL,
    kind text NOT NULL CHECK (kind IN ('HUMAN', 'LOCAL_DEVELOPMENT', 'SYSTEM_SEED', 'PUBLIC_DEMO_SESSION',
                                       'LEGACY_UNCLASSIFIED')),
    seq bigint GENERATED ALWAYS AS IDENTITY UNIQUE,
    UNIQUE (organization_id, display_name),
    UNIQUE (organization_id, user_id)
);

CREATE FUNCTION baec.users_guard() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'users are never deleted' USING ERRCODE = 'restrict_violation';
    END IF;
    IF NEW.organization_id IS DISTINCT FROM OLD.organization_id THEN
        RAISE EXCEPTION 'a user cannot change organization' USING ERRCODE = 'restrict_violation';
    END IF;
    IF NEW.kind IS DISTINCT FROM OLD.kind THEN
        RAISE EXCEPTION 'a user kind never changes' USING ERRCODE = 'restrict_violation';
    END IF;
    IF (NEW.user_id, NEW.created_at, NEW.seq) IS DISTINCT FROM (OLD.user_id, OLD.created_at, OLD.seq) THEN
        RAISE EXCEPTION 'only a user''s display name and activation can change' USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER users_guard BEFORE UPDATE OR DELETE ON baec.users FOR EACH ROW EXECUTE FUNCTION baec.users_guard();
CREATE TRIGGER organizations_append_only BEFORE UPDATE OR DELETE ON baec.organizations
    FOR EACH ROW EXECUTE FUNCTION baec.refuse_change();

-- seq orders one identity store's audit (SQLite numbers each data root from 1), so it is unique per organization.
CREATE TABLE baec.identity_audit (
    seq bigint GENERATED BY DEFAULT AS IDENTITY,
    organization_id text NOT NULL,
    occurred_at timestamptz NOT NULL,
    event_type text NOT NULL CHECK (event_type IN ('USER_CREATED', 'USER_RENAMED', 'USER_DEACTIVATED',
                                                   'USER_REACTIVATED', 'KIND_CLASSIFIED_BY_MIGRATION')),
    user_id text NOT NULL,
    detail text NOT NULL,
    PRIMARY KEY (organization_id, seq),
    FOREIGN KEY (organization_id, user_id) REFERENCES baec.users (organization_id, user_id)
);

