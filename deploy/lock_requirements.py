"""Generate deploy/requirements.lock from deploy/requirements.in. (V0.4 Phase 5; IMPLEMENTATION.)

    python deploy/lock_requirements.py            write deploy/requirements.lock
    python deploy/lock_requirements.py --check    exit 1 if the lock does not match requirements.in exactly

For every `name==version` line it records the SHA-256 of every file PyPI publishes for that exact version (all
platforms), so `pip install --require-hashes --no-deps -r requirements.lock` installs exactly these versions on any
platform the image is built for, and refuses a file whose content differs. It changes no version: the closure in
requirements.in is reviewed by hand. Needs network access to pypi.org; the build itself does not run this.
"""

from __future__ import annotations

import json
import re
import sys
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "requirements.in"
LOCK = HERE / "requirements.lock"
HEADER = ("# Generated by deploy/lock_requirements.py from deploy/requirements.in. Do not edit by hand.\n"
          "# Install with: pip install --require-hashes --no-deps -r requirements.lock\n")


def pins(text: str) -> list[tuple[str, str]]:
    found = []
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        match = re.fullmatch(r"([A-Za-z0-9][A-Za-z0-9._-]*)==([A-Za-z0-9.+!-]+)", line)
        if match is None:
            raise SystemExit(f"not an exact pin: {line!r}")
        found.append((match[1].lower(), match[2]))
    names = [n for n, _ in found]
    if len(names) != len(set(names)):
        raise SystemExit("a package is pinned twice")
    return found


def hashes(name: str, version: str) -> list[str]:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as response:
        release = json.load(response)
    found = sorted({f["digests"]["sha256"] for f in release["urls"] if not f.get("yanked")})
    if not found:
        raise SystemExit(f"{name}=={version} has no published files")
    return found


def render(source: str) -> str:
    lines = [HEADER]
    for name, version in sorted(pins(source)):
        lines.append(f"{name}=={version} \\\n" + " \\\n".join(f"    --hash=sha256:{h}" for h in hashes(name, version))
                     + "\n")
    return "".join(lines)


def main(argv: list[str]) -> int:
    rendered = render(SOURCE.read_text(encoding="utf-8"))
    if argv[1:] == ["--check"]:
        current = LOCK.read_text(encoding="utf-8") if LOCK.exists() else ""
        print("lock matches requirements.in" if current == rendered else "lock differs from requirements.in")
        return 0 if current == rendered else 1
    LOCK.write_text(rendered, encoding="utf-8")
    print(f"wrote {LOCK.name}: {len(pins(SOURCE.read_text(encoding='utf-8')))} packages")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
